/**
 * Finds deals the solver can win and writes them to src/engine/winnableSeeds.ts, for
 * variants and options where solving at runtime is too slow.
 *
 *   node scripts/find-winnable.ts                      every option set, then write
 *   node scripts/find-winnable.ts --only spider:suits=2 --count 100 --ms 20000 --minutes 30
 *       prints one JSON line for that set instead of writing
 *   node scripts/find-winnable.ts --write < lines.jsonl
 *       merges printed lines into the file
 */
import { randomInt } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { allOptionSets, dealKey } from "../src/engine/dealKey.ts";
import { solve } from "../src/engine/solver.ts";
import { VARIANTS } from "../src/engine/variants/index.ts";
import { WINNABLE_SEEDS } from "../src/engine/winnableSeeds.ts";

const OUTPUT = new URL("../src/engine/winnableSeeds.ts", import.meta.url);

const { values } = parseArgs({
  options: {
    only: { type: "string" },
    count: { type: "string", default: "150" },
    ms: { type: "string", default: "3000" },
    minutes: { type: "string", default: "10" },
    write: { type: "boolean", default: false },
  },
});

interface Found {
  readonly key: string;
  readonly seeds: readonly number[];
}

function search(key: string, count: number, perSeedMs: number, minutes: number): Found {
  for (const variant of VARIANTS) {
    for (const options of allOptionSets(variant)) {
      if (dealKey(variant, options) !== key) {
        continue;
      }
      const seeds: number[] = [];
      const deadline = Date.now() + minutes * 60_000;
      let tried = 0;
      while (seeds.length < count && Date.now() < deadline) {
        const seed = randomInt(2 ** 32);
        tried += 1;
        const result = solve(variant, variant.deal(seed, options), {
          maxNodes: Number.POSITIVE_INFINITY,
          maxMs: perSeedMs,
        });
        if (result.status === "solved") {
          seeds.push(seed);
        }
      }
      process.stderr.write(`${key}: ${seeds.length} of ${tried} tried\n`);
      return { key, seeds };
    }
  }
  throw new Error(`Unknown deal key: ${key}`);
}

function parseFound(line: string): Found {
  const value: unknown = JSON.parse(line);
  if (
    typeof value === "object" &&
    value !== null &&
    "key" in value &&
    typeof value.key === "string" &&
    "seeds" in value &&
    Array.isArray(value.seeds) &&
    value.seeds.every((seed) => Number.isInteger(seed))
  ) {
    return { key: value.key, seeds: value.seeds.filter((seed) => typeof seed === "number") };
  }
  throw new Error(`Bad line: ${line}`);
}

function write(found: readonly Found[]): void {
  const merged: Record<string, readonly number[]> = { ...WINNABLE_SEEDS };
  for (const { key, seeds } of found) {
    merged[key] = [...new Set([...(merged[key] ?? []), ...seeds])].toSorted((a, b) => a - b);
  }
  const keys = Object.keys(merged).toSorted();
  const body = keys.map((key) => `  ${JSON.stringify(key)}: [${(merged[key] ?? []).join(", ")}],`);
  writeFileSync(
    OUTPUT,
    [
      "// Generated by scripts/find-winnable.ts: deals the solver has won, for each variant",
      "// and set of deal options. Regenerate rather than editing by hand.",
      "export const WINNABLE_SEEDS: Readonly<Record<string, readonly number[]>> = {",
      ...body,
      "};",
      "",
    ].join("\n"),
  );
}

if (values.write) {
  const lines = readFileSync(0, "utf8")
    .split("\n")
    .filter((line) => line.trim().length > 0);
  write(lines.map((line) => parseFound(line)));
} else {
  const keys =
    values.only === undefined
      ? VARIANTS.flatMap((variant) =>
          allOptionSets(variant).map((options) => dealKey(variant, options)),
        )
      : [values.only];
  const found = keys.map((key) =>
    search(key, Number(values.count), Number(values.ms), Number(values.minutes)),
  );
  if (values.only === undefined) {
    write(found);
  } else {
    process.stdout.write(`${JSON.stringify(found[0])}\n`);
  }
}
